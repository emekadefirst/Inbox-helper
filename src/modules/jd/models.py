from tortoise import fields
from src.common.base_model import BaseModel


class JobDescription(BaseModel):
    title = fields.CharField(255, null=False, unique=True)
    description = fields.TextField(null=True)
    responseibilities = fields.JSONField(null=True)
    qualifications = fields.JSONField(null=True)
    note_to_intelligence = fields.TextField(null=True) # extra note by the author to the llm for better understanding of the job description
    generated_classification = fields.JSONField(null=True) # generated by the llm


    class Meta:
        table = "job_descriptions"
        indexes = [("title", "id")]


